"""Build mod/le_catalogue.txt: every LE_ prefab the game ships, for the Place Actors palette.

The palette used to list only LE classes already loaded in memory, and the station loads just a couple,
so the editor offered 2 items out of ~97. This walks an FModel JSON export of the game content and
records every LE_ BlueprintGeneratedClass with its full class path. The server loads any of them on
demand when one is spawned (specedit.h, SeResolveEditorClass), so the palette is no longer capped by
what the map happened to reference.

    python SpecEditor/tools/make_catalogue.py [export root]

The export root defaults to Output/Exports (FModel's "Export Raw Data (.json)" of A2/Content).
Output lines are  <category>|<class path> , e.g.
    Meshes / Golf|/Game/A2/Prefabs/Meshes/Golf/LE_SM_GolfRampA.LE_SM_GolfRampA_C
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
EXPORTS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'Output', 'Exports')
OUT = os.path.join(HERE, '..', 'mod', 'le_catalogue.txt')


def category(rel_dir):
    """A2/Content/A2/Prefabs/Meshes/Golf -> 'Meshes / Golf'; the palette groups on this."""
    parts = rel_dir.replace('\\', '/').split('/')
    if 'Content' in parts:
        parts = parts[parts.index('Content') + 1:]
    if parts and parts[0] == 'A2':
        parts = parts[1:]
    if parts and parts[0] == 'Prefabs':
        parts = parts[1:] or ['Prefabs']
    return ' / '.join(parts) if parts else 'Prefabs'


def class_name(path):
    """The generated class's real name, read from the export rather than assumed to be <asset>_C."""
    try:
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
    except (OSError, ValueError):
        return None
    for obj in data if isinstance(data, list) else [data]:
        if isinstance(obj, dict) and obj.get('Type') == 'BlueprintGeneratedClass':
            return obj.get('Name')
    return None


entries = []
for dirpath, _, files in os.walk(EXPORTS):
    for fn in files:
        if not (fn.startswith('LE_') and fn.endswith('.json')):
            continue
        full = os.path.join(dirpath, fn)
        cls = class_name(full)
        if not cls:
            continue                                   # not a spawnable class (e.g. a bare mesh)
        rel = os.path.relpath(dirpath, EXPORTS).replace('\\', '/')
        # <export>/A2/Content/<x> is /Game/<x>
        if '/Content/' not in '/' + rel + '/':
            continue
        game_dir = '/Game/' + rel.split('Content/', 1)[1] if 'Content/' in rel else '/Game'
        asset = fn[:-len('.json')]
        entries.append((category(rel), f'{game_dir}/{asset}.{cls}'))

entries.sort()
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('# Generated by tools/make_catalogue.py -- every LE_ prefab class the game ships.\n')
    f.write('# <category>|<class path>. The server loads a class on demand when it is spawned.\n')
    for cat, path in entries:
        f.write(f'{cat}|{path}\n')

cats = {}
for c, _ in entries:
    cats[c] = cats.get(c, 0) + 1
print(f'{len(entries)} LE classes -> {os.path.normpath(OUT)}')
for c in sorted(cats):
    print(f'  {cats[c]:3d}  {c}')
